export type Block =
  /** обычный абзац */
  | { type: "text"; text: string }
  /** маркированный список */
  | { type: "list"; items: string[] }
  /** подзаголовок внутри раздела */
  | { type: "subhead"; text: string }
  /** плитки «название + пояснение» */
  | { type: "cards"; items: { title: string; text: string }[] }
  /** крупные числа */
  | { type: "stats"; items: { value: string; label: string }[] }
  /** сгруппированный список (коннекторы по категориям) */
  | {
      type: "groups";
      items: { title: string; items: { name: string; text: string }[] }[];
    }
  /** выделенная врезка-предупреждение */
  | { type: "note"; text: string; email?: string };

export type ReleaseSection = {
  /** якорь и ключ в оглавлении */
  id: string;
  title: string;
  blocks: Block[];
};

export type Release = {
  /** часть URL: /whats-new/<slug> */
  slug: string;
  /** номер версии, как в продукте */
  version: string;
  /** заголовок карточки и страницы */
  title: string;
  /** машинная дата для <time> и сортировки */
  date: string;
  /** дата прописью, как в источнике */
  dateLabel: string;
  /** метка на карточке разводящей */
  tag: string;
  /** лид — он же описание карточки и meta description */
  summary: string;
  /** короткий перечень главного для карточки на разводящей */
  highlights: string[];
  sections: ReleaseSection[];
};

