"use client";

import { useEffect, useState } from "react";

/**
 * Карточка «кейсы на подходе» — последняя в ленте `/success-stories`.
 *
 * Своей карточки в макете нет: это заглушка последней ячейки сетки. Кейсов
 * сейчас четыре, широкая занимает оба столбца, и в нижнем ряду остаётся пустое
 * место — вместо дыры там стоит обещание. Форма взята у обычной узкой карточки
 * (Card / Case / Small 5130:27393): те же скругление 24, подложка, отступы
 * 24/32 и минимальная высота 480, поэтому ряд не разъезжается.
 *
 * Отрасль в заголовке меняется сама: список ниже — то, над чем идёт работа.
 * Слово набирается по буквам, остальная строка стоит на месте — так блок не
 * дёргает ленту и не перетягивает внимание с самих кейсов.
 */

/**
 * Отрасли в родительном падеже: строка читается как «кейсами для банков».
 * Здесь те направления, по которым разборы готовятся, — список правится
 * руками, из справочника кейсов его не собрать: там только опубликованное.
 */
const INDUSTRIES = [
  "банков",
  "ритейла",
  "логистики",
  "промышленности",
  "энергетики",
  "нефтегаза",
  "агропрома",
  "ИТ",
  "телекома",
] as const;

/**
 * Тайминги набора, мс. Буква за 45 — быстрее, чем печатает человек, но глаз
 * успевает прочесть слово по мере появления. Стирание вдвое быстрее: это
 * служебное движение, и тянуть его незачем.
 */
const TYPE = 45;
const ERASE = 22;
/** Набранное слово стоит на месте, прежде чем стереться. */
const HOLD = 2000;
/** Пауза с пустой строкой перед следующим словом. */
const SWITCH = 320;

export function SoonCard() {
  /*
    На сервере и без JS в строке стоит первое слово целиком: пустая строка
    «Работаем над новыми кейсами для» без окончания читалась бы как ошибка вёрстки.
  */
  const [typed, setTyped] = useState<string>(INDUSTRIES[0]);
  /** Курсор показываем только когда идёт набор. */
  const [live, setLive] = useState(false);

  useEffect(() => {
    /*
      Системная настройка «меньше движения» — не украшательство: для части
      людей бегущий текст это головокружение и тошнота. В этом режиме слово
      просто стоит первым из списка, без набора и курсора.
    */
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    let timer = 0;
    let word = 0;
    let length = 0;
    let phase: "type" | "hold" | "erase" = "type";

    /*
      Одна цепочка таймеров вместо интервала: шаги разной длины (буква,
      пауза, стирание), и интервал пришлось бы городить на счётчиках. При
      размонтировании гасится один таймер — ничего не продолжает тикать.
    */
    const step = () => {
      const current = INDUSTRIES[word];

      if (phase === "type") {
        length += 1;
        setTyped(current.slice(0, length));
        if (length === current.length) {
          phase = "hold";
          timer = window.setTimeout(step, HOLD);
        } else {
          timer = window.setTimeout(step, TYPE);
        }
        return;
      }

      if (phase === "hold") {
        phase = "erase";
        timer = window.setTimeout(step, ERASE);
        return;
      }

      length -= 1;
      setTyped(current.slice(0, length));
      if (length === 0) {
        word = (word + 1) % INDUSTRIES.length;
        phase = "type";
        timer = window.setTimeout(step, SWITCH);
      } else {
        timer = window.setTimeout(step, ERASE);
      }
    };

    /* Первое слово уже набрано на сервере — начинаем с паузы и стирания. */
    length = INDUSTRIES[0].length;
    phase = "hold";
    setLive(true);
    timer = window.setTimeout(step, HOLD);

    return () => window.clearTimeout(timer);
  }, []);

  return (
    <article className="relative flex min-h-[280px] flex-col overflow-hidden rounded-24 bg-neutral-100 lg:min-h-[480px]">
      {/*
        Содержимого немного, поэтому оно стоит по центру высоты: прижатое к
        верху, оно оставляло бы под собой полкарточки пустоты рядом с плотными
        карточками кейсов.
      */}
      <div className="flex flex-1 flex-col justify-center gap-16 p-24 lg:gap-24 lg:p-32">
        {/*
          Крупно, но тише метрики: у кейсов результат набран Display/L (96),
          здесь H3 на телефоне и H2 (36) на десктопе. Обещание не должно
          спорить с цифрами, которые уже подтверждены.

          Для диктора строка читается один раз и целиком, с перечислением
          отраслей: слово, которое меняется само по себе, он повторял бы
          бесконечно.
        */}
        {/*
          Высота строки зарезервирована под три строки (3 × 1.2em): «для
          промышленности» переносит заголовок на строку больше, и без запаса
          подпись под ним подпрыгивала бы при каждой смене слова. Считаем в
          em, а не в пикселях: кегль на телефоне и десктопе разный.
        */}
        <p className="min-h-[3.6em] text-h3 font-medium text-text-secondary md:text-h2">
          <span className="sr-only">
            Работаем над новыми кейсами для {INDUSTRIES.join(", ")}.
          </span>
          <span aria-hidden>
            Работаем над новыми кейсами для{" "}
            {/*
              Слово набирается по буквам и стоит последним в строке: то, что
              перед ним, не двигается, пока оно растёт. Жирное начертание
              отделяет меняющуюся часть от постоянной. «Для» остаётся в
              неизменной части: предлог у всех отраслей один.
            */}
            <span className="font-bold whitespace-nowrap text-text-primary">
              {typed}
              {live ? <span className="type-caret" /> : null}
            </span>
          </span>
        </p>

        <p className="text-body-l text-text-secondary">
          Скоро здесь будет ещё больше историй о&nbsp;том, как компании
          используют GigaCowork.
        </p>
      </div>
    </article>
  );
}

export default SoonCard;
