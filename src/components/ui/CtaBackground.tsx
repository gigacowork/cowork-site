import { HeroImage } from "@/components/ui/HeroImage";

/**
 * Фон блоков «Готовы делегировать работу ИИ-агентам?» и остальных CTA.
 *
 * Раньше это был градиент — один и тот же, продублированный пятью константами
 * по страницам. Теперь картинка, и чтобы она не расползлась такими же копиями,
 * подложка вынесена сюда: во всех CTA лежит один и тот же элемент.
 *
 * Кадры разные под ширину экрана: десктопный 2880×974 (почти 3:1, широкая
 * панорама), мобильный 1170×807 (3:2, тот же мотив, но кадрирован под узкий
 * экран). Это не один файл в двух размерах, а две разные обрезки, поэтому
 * подмену делает `<picture media>` — лишний файл при этом не скачивается.
 *
 * Класс-заливка (`CTA_FALLBACK`) ставится на сам блок: пока картинка грузится,
 * секция не мигает белым, а фон совпадает с ней по тону. Блоку нужны ещё
 * `relative isolate overflow-hidden` — картинка позиционируется по нему и
 * обрезается по его скруглению.
 */
export const CTA_FALLBACK = "bg-[#f7f8fa]";

export function CtaBackground() {
  return (
    <HeroImage
      desktop="/img/cta/cta-bg.webp"
      mobile="/img/cta/cta-bg-mob.webp"
      className="pointer-events-none absolute inset-0 -z-10 size-full object-cover"
    />
  );
}

export default CtaBackground;
