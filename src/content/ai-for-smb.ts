export function smbLessonPath(slug: string) {
  const lesson = SMB_LESSONS.find((item) => item.slug === slug);
  if (!lesson) throw new Error(`Unknown SMB lesson slug: ${slug}`);
  return `${SMB_LESSONS_PATH}/lesson-${lesson.number}`;
}
