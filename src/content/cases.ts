export const AVAILABLE_INDUSTRIES = INDUSTRIES.filter((industry) =>
  VISIBLE_CASES.some((item) => item.industry === industry),
);

export const AVAILABLE_ROLES = ROLES.filter((role) =>
  VISIBLE_CASES.some((item) => item.role === role),
);

