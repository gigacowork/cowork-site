/** Кейсы, у которых есть детальная страница. */
export const CASES_WITH_STORY = VISIBLE_CASES.filter(
  (item): item is CaseStudy & { slug: string; story: CaseStory } =>
    Boolean(item.slug && item.story),
);

export function findCase(slug: string) {
  return CASES_WITH_STORY.find((item) => item.slug === slug);
}
