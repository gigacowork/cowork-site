/* ─────────────────────────────── типы ──────────────────────────────────── */

export type CaseTag = {
  label: string;
  /**
   * Имя файла в public/img/icons без расширения. Нет — чип рисуется одной
   * подписью: обвязка это умеет, но у всех текущих кейсов иконки есть.
   *
   * `building` и `truck` (22.09.2026) — единственные две иконки, нарисованные
   * не выгрузкой из Figma: в наборе Icon (354:151) зданий и грузовиков нет.
   * Геометрия повторяет набор: 24×24, обводка 1, скруглённые концы и стыки.
   * Появятся в дизайн-системе — заменить выгрузкой плагин-API.
   */
  icon?: string;
};

/** Логотип клиента. Нет — в слоте рисуется название компании текстом. */
export type CaseLogo = {
  src: string;
  width: number;
  height: number;
  className: string;
};

/** Блок текста детальной страницы. Порядок в массиве = порядок на странице. */
export type StoryBlock =
  | { type: "heading"; text: string }
  | { type: "text"; text: string }
  /** Врезка на светло-серой подложке — Article Callout 5173:54004 */
  | { type: "callout"; text: string }
  /** Кадр интерфейса с подписью — Article Image 5173:53988 */
  | { type: "image"; src?: string; caption: string }
  /** Цитата с кавычкой — Info Card 5173:54044 */
  | { type: "quote"; text: string[]; author: string; role: string }
  /** Сноска мелким серым в конце статьи — 5173:54057 */
  | { type: "disclaimer"; text: string };

export type StoryMetric = {
  /** «≥», «>», «+» — всё, что стоит перед числом */
  prefix?: string;
  value: string;
  /** «%», «п. п.» — набирается Heading/H1, не уменьшается вместе с числом */
  suffix?: string;
  /** «\n» — жёсткий перенос из макета */
  label: string;
};

export type CaseStory = {
  /** H1 детальной страницы */
  title: string;
  /** Подзаголовок hero */
  lead: string;
  metrics: StoryMetric[];
  company: {
    name: string;
    description: string;
    /** «Область автоматизации» */
    automation: string;
    /** Чипы «Технологии». Пусто — блок не рисуется. */
    technologies: string[];
  };
  blocks: StoryBlock[];
};

export type CaseStudy = {
  /** Есть — собирается детальная страница и карточка ведёт на неё. */
  slug?: string;
  company: string;
  metric: string;
  metricCaption: string;
  description: string;
  /** Короткое описание для карточки в ленте кейсов, если оно своё. */
  cardDescription?: string;
  logo?: CaseLogo;
  tags: [CaseTag, CaseTag];
  industry: Industry;
  role: Role;
  /**
   * Кадр в широкой карточке — два файла: на телефоне он лежит сверху полосой
   * 358×220, на десктопе стоит справа 564×432. Это разная обрезка, а не один
   * файл в двух размерах, поэтому пара, а не srcset по плотности.
   * Нет — рисуется заглушка.
   */
  photo?: { desktop: string; mobile: string };
  /** Градиент карточки на главной — свой угол из макета. */
  gradientClassName: string;
  /** Ждёт материалов: не выводится ни на главной, ни в ленте кейсов. */
  hidden?: boolean;
  story?: CaseStory;
};

