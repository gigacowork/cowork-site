/**
 * Форматирование чисел в разметке.
 *
 * Отдельный модуль, а не функция внутри `CountUp`: тот помечен `"use client"`,
 * и всё, что из него экспортируется, для серверных компонентов становится
 * ссылкой на клиент — вызвать при рендере страницы нельзя. А разбивать разряды
 * нужно в обоих местах сразу: сервер выводит готовое число, счётчик потом
 * пересобирает его на каждом кадре, и разделитель обязан быть один и тот же.
 */

/**
 * Разделитель разрядов — неразрывный пробел: число не должно разорваться
 * переносом строки посреди разряда.
 */
export const GROUP_SEPARATOR = " ";

/** 120000000 → «120 000 000». */
export const groupDigits = (value: number) =>
  String(value).replace(/\B(?=(\d{3})+(?!\d))/g, GROUP_SEPARATOR);
