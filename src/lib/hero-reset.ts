/**
 * Сигнал «вернуть hero главной в исходное состояние».
 *
 * Шапка и чат в hero — независимые компоненты в разных ветках дерева: один
 * лежит в общем макете, другой на странице. Тянуть состояние чата наверх в
 * контекст ради одного клика по логотипу не стоит — оно живёт в `HeroChat` и
 * больше никому не нужно. Поэтому связь односторонняя и через событие окна:
 * шапка его шлёт, чат слушает. Нет чата на странице — событие просто некому
 * поймать, и ничего не происходит.
 */

export const HERO_RESET_EVENT = "cowork:hero-reset";

/** Шлёт сигнал. Вызывать только на клиенте. */
export function requestHeroReset() {
  window.dispatchEvent(new Event(HERO_RESET_EVENT));
}
