/**
 * Синхронный отрыв липких соседей стопки.
 *
 * В скролл-стори рядом со стопкой живут другие липкие элементы: подпись слева
 * и, на /ai-platform, заголовок секции. Открепиться они должны вместе с
 * карточками — иначе стопка уезжает вверх, а подпись ещё висит в пустоте
 * (на «ИИ-агентах» это было заметнее всего: карточки уходили на 275 раньше).
 *
 * Момент открепления у липкого элемента один и тот же: когда до низа общего
 * контейнера остаётся ровно его высота плюс смещение сверху. У карточки это
 * `stickyTop + её высота`, у подписи — `её top + её высота`, и второе обычно
 * меньше, поэтому она и держится дольше. Разницу дописываем прозрачным хвостом
 * снизу: липкий диапазон удлиняется на неё, и оба отрываются одновременно.
 *
 * Хвост — `padding-bottom`, а не отступ: он входит в габарит, по которому
 * считается открепление, и при этом ничего не двигает — подпись прозрачная, а
 * ячейка под ней втрое выше.
 *
 * Подписи выше карточки хвоста мало: ей нужен отрицательный. Такую подпись
 * подрезаем по высоте — бокс становится ровно во весь диапазон, а содержимое
 * выходит за него и рисуется как было. Видно ничего не станет: бокс
 * прозрачный, ячейка под подписью втрое выше, и в колонке под ней ничего
 * нет. Колонка при этом `flex-direction: column`, у её детей `min-height:
 * auto` — они не ужимаются, а выступают.
 */

/** Момент отрыва стопки: до низа контейнера осталось столько. */
export function stackRelease(cards: HTMLElement[], stickyTop: number): number {
  /*
    Считаем по первой карточке. Обычно это всё равно: карточки одной высоты.
    Расходятся они только на /ai-platform, где первое превью на 26 ниже
    остальных, — и там замер показывает, что отрыв стопки идёт именно по
    первой: с высотой последней подпись уходит на 25 раньше карточек.
  */
  return stickyTop + cards[0].offsetHeight;
}

/** Длина хвоста для элемента, чтобы он открепился вместе со стопкой. */
export function stickyTailFor(el: HTMLElement, release: number): number {
  const top = parseFloat(getComputedStyle(el).top) || 0;
  return Math.max(0, Math.round(release - top - el.offsetHeight));
}

/**
 * Приводит липкий диапазон элемента к диапазону стопки.
 *
 * Прошлые правки снимаются до замера, иначе они войдут в собственную высоту.
 */
export function applyStickyTail(el: HTMLElement, release: number): void {
  clearStickyTail(el);

  const top = parseFloat(getComputedStyle(el).top) || 0;
  /* Сколько высоты помещается в диапазон стопки. */
  const room = Math.round(release - top);
  if (room <= 0) return;

  const natural = el.offsetHeight;
  if (natural <= room) el.style.paddingBottom = `${room - natural}px`;
  else el.style.height = `${room}px`;
}

/** Снимает хвост и подрезку — размеры снова из разметки. */
export function clearStickyTail(el: HTMLElement): void {
  el.style.removeProperty("padding-bottom");
  el.style.removeProperty("height");
}
