/**
 * Данные страниц «Для кого» (/use_cases/*).
 *
 * Все восемь страниц собираются одним шаблоном — см.
 * src/app/(site)/use_cases/[slug]/page.tsx. Здесь только контент, вёрстки нет.
 *
 * Адреса взяты из ПРОЕКТ_COWORK_RU.md (раздел «Релиз 1»), порядок в массиве —
 * это же порядок в выпадающем меню «Для кого» и порядок карточек в блоке
 * «Не тратьте часы…» на главной, чтобы одно не разъезжалось с другим.
 *
 * Откуда тексты:
 *   • finance — макет Finance / Desktop (2484:31045) и блок «Применение»
 *     (2787:16125), дословно;
 *   • ceo — файл «Управление.docx», дословно;
 *   • остальные роли — черновик под структуру макета, а не согласованный
 *     контент: своих фреймов и текстов у них пока нет.
 *
 * Любой блок заменяется без правки вёрстки — меняется только этот файл.
 * Секции с пустыми данными (метрики, преимущества) шаблон просто не рисует.
 */

export type UseCaseMetric = {
  /** знак перед числом того же кегля («×» у юристов) */
  prefix?: string;
  /** число до знака; анимируется счётчиком */
  value: number;
  /** знак после числа; у части метрик его нет */
  suffix?: string;
  /** подпись под числом; «\n» — жёсткий перенос из макета */
  caption: string;
};

export type UseCaseScenario = {
  title: string;
  /** абзацы описания; между ними в макете пустая строка */
  paragraphs: string[];
  /** «эффекты» — маркированный список под описанием */
  effects: string[];
};

export type UseCaseStep = {
  title: string;
  paragraphs: string[];
  /** маркированный список под абзацами (перечень отчётов в бухгалтерии) */
  bullets?: string[];
  /** подпись под кнопкой воспроизведения; в части макетов её нет */
  videoLabel?: string;
};

export type UseCaseTag = { label: string; icon: string };

/** Секции шаблона между hero и финальным CTA. */
export type UseCaseSection =
  | "metrics"
  | "scenarios"
  | "steps"
  | "process"
  | "benefits";

/**
 * Порядок из большинства макетов: метрики, «Применение», «Решения»,
 * «Как это работает», «Преимущества».
 */
export const DEFAULT_ORDER: UseCaseSection[] = [
  "metrics",
  "scenarios",
  "steps",
  "process",
  "benefits",
];

/** Блок «Как это работает»: ряд пронумерованных шагов и плашка под ними. */
export type UseCaseProcess = {
  kicker: string;
  /** Заголовок; в тексте ИТ-поддержки его нет — остаётся один кикер. */
  title?: string;
  steps: { number: string; title: string; text: string }[];
  callout?: { title: string; text: string };
};

export type UseCaseBenefit = {
  title: string;
  paragraphs: string[];
  /** Теги под карточкой. Нет в тексте роли — карточка идёт без них. */
  tags?: UseCaseTag[];
};

export type UseCase = {
  /** сегмент адреса: /use_cases/<slug> */
  slug: string;
  /** подпись в выпадающем меню «Для кого» */
  navLabel: string;
  /** id карточки в блоке «Не тратьте часы…» на главной */
  cardId: string;
  /** H1; «\n» — перенос строки из макета */
  title: string;
  /** абзацы под заголовком */
  intro: string[];
  /**
   * Фон hero, десктопный кадр (2880×1520) из папки «Исходники Изображения
   * в HERO». Для ролей, у которых исходника нет, поле пустое — тогда шаблон
   * рисует градиент из макета (2616:11205).
   */
  heroImage?: string;
  /**
   * Мобильный кадр (1170×1680). Это не тот же файл в другом размере, а своя
   * обрезка под вертикальный экран, поэтому путь задаётся отдельно.
   */
  heroImageMobile?: string;
  /**
   * Блок метрик. Пустой массив или отсутствие поля — секция не выводится:
   * у некоторых ролей согласованных цифр пока нет.
   */
  metrics?: UseCaseMetric[];
  scenariosTitle: string;
  scenarios: UseCaseScenario[];
  /** Заголовок блока «Решения». Без него секция идёт только с кикером. */
  stepsTitle?: string;
  /** Короткая строка-связка под заголовком блока «Решения». */
  stepsLead?: string;
  steps: UseCaseStep[];
  /** Заголовок блока преимуществ. Без него секция идёт только с кикером. */
  benefitsTitle?: string;
  /**
   * Кикер над блоком преимуществ. `null` — кикера нет вовсе: так у закупок,
   * где блок идёт обычным заголовком.
   */
  benefitsKicker?: string | null;
  /**
   * Порядок секций между hero и финальным CTA. По умолчанию — DEFAULT_ORDER.
   * Секция без данных пропускается, поэтому лишние ключи безопасны.
   */
  order?: UseCaseSection[];
  /** Короткая строка-связка под заголовком блока преимуществ. */
  benefitsLead?: string;
  benefits: UseCaseBenefit[];
  /** Блок «Как это работает» (2919:17802). */
  process?: UseCaseProcess;
  /** Свой заголовок финального CTA вместо общего по умолчанию. */
  ctaTitle?: string;
};

