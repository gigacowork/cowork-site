export const USE_CASE_SLUGS = USE_CASES.map((item) => item.slug);

export function getUseCase(slug: string): UseCase | undefined {
  return USE_CASES.find((item) => item.slug === slug);
}

/**
 * Адрес страницы роли по слагу — с проверкой, что такая роль есть.
 *
 * Бросает исключение, а не возвращает undefined: вызывается из серверных
 * компонентов, то есть на сборке. Опечатка в слаге валит билд сразу, а не
 * превращается в мёртвую ссылку на живом сайте.
 */
export function useCaseHref(slug: string): string {
  const found = USE_CASES.find((item) => item.slug === slug);
  if (!found) throw new Error(`Неизвестная роль use_cases: «${slug}»`);
  return `/use_cases/${found.slug}`;
}

/** Адрес страницы роли по id карточки блока «Не тратьте часы…». */
export function useCaseHrefByCardId(cardId: string): string | undefined {
  const found = USE_CASES.find((item) => item.cardId === cardId);
  return found && `/use_cases/${found.slug}`;
}
